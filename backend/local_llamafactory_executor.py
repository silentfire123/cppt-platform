from __future__ import annotations

"""Safe local LLaMA-Factory process executor.

The only subprocess call in this module is ``create_subprocess_exec``.  The
user task never supplies a command or shell fragment; the executable comes
from a server-side environment setting and the YAML path is generated by the
platform.
"""

import asyncio
import hashlib
import json
import os
import re
import shlex
import shutil
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, AsyncIterator, Mapping

from backend.llamafactory import (
    LlamaFactoryTask,
    dataset_info_for_task,
    platform_to_llamafactory_config,
    dump_yaml,
)
from backend.store import (
    NUM_EPOCHS_PATTERN,
    TOTAL_STEPS_PATTERN,
    infer_metric_step,
    parse_trainer_values,
)
from backend.training_artifacts import read_training_artifacts
from backend.training_executor import ExecutionHandle, TrainingEvent, TrainingExecutor


class LocalLlamaFactoryExecutor(TrainingExecutor):
    def __init__(
        self,
        *,
        work_root: Path | None = None,
        command: str | list[str] | None = None,
        python_executable: str | None = None,
        stop_timeout: float = 30,
    ) -> None:
        self.work_root = (work_root or Path(os.environ.get("XUNTUI_TRAINING_WORKDIR", "./runtime/training-work"))).expanduser().resolve()
        self.command = command if command is not None else os.environ.get("XUNTUI_LLAMA_FACTORY_COMMAND", "llamafactory-cli")
        self.python_executable = python_executable or os.environ.get("XUNTUI_TRAINING_PYTHON")
        self.stop_timeout = stop_timeout
        self._handles: dict[str, ExecutionHandle] = {}

    @staticmethod
    def _task_id(task: Mapping[str, Any]) -> str:
        value = task.get("taskId") or task.get("id")
        if not value:
            raise ValueError("训练任务缺少 taskId/id。")
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}", str(value)):
            raise ValueError("taskId 包含不安全字符。")
        return str(value)

    @staticmethod
    def _command_argv(command: str | list[str]) -> list[str]:
        if isinstance(command, list):
            argv = [str(item) for item in command]
        else:
            argv = shlex.split(str(command, ), posix=True)
        if not argv or any(not item or any(ch in item for ch in "\x00\r\n") for item in argv):
            raise ValueError("LLaMA-Factory 命令配置为空或包含非法字符。")
        return argv

    def _launch_argv(self, config_path: str) -> list[str]:
        """Build administrator-controlled argv without incorrectly prefixing console scripts."""
        command_argv = self._command_argv(self.command)
        if self.python_executable:
            python_executable = str(self.python_executable)
            if not python_executable or any(ch in python_executable for ch in "\x00\r\n"):
                raise ValueError("训练 Python 配置为空或包含非法字符。")
            # A console script (e.g. llamafactory-cli) must be executed
            # directly. Python is only appropriate for `-m` or an explicit .py.
            if command_argv[0] == "-m" or Path(command_argv[0]).suffix.lower() == ".py":
                command_argv = [python_executable, *command_argv]
        return [*command_argv, "train", config_path]

    def _canonical_task(self, task: Mapping[str, Any], output_dir: Path) -> LlamaFactoryTask:
        raw = dict(task)
        raw["taskId"] = raw.get("taskId") or raw.get("id")
        raw.setdefault("framework", "llamafactory")
        raw.setdefault("executionMode", "local")
        raw.setdefault("provider", "local")
        raw.setdefault("outputName", raw.get("name") or raw["taskId"])
        raw["datasetId"] = raw.get("datasetId") or raw.get("dataset_id")
        raw["taskType"] = raw.get("taskType") or raw.get("task_type") or "SFT"
        raw["tuningMode"] = raw.get("tuningMode") or raw.get("tuning_mode") or "lora"
        raw["dataset"] = {
            **dict(raw.get("dataset") or {}),
            "paths": {
                **{key: raw[key] for key in ("trainPath", "validationPath", "testPath", "challengePath") if raw.get(key)},
                # Prepared/copy-isolated paths must override the legacy task-level
                # paths; otherwise validation can escape the controlled workdir.
                **dict((raw.get("dataset") or {}).get("paths") or {}),
            },
            "template": raw.get("template") or (raw.get("dataset") or {}).get("template"),
            "formatting": raw.get("formatting") or (raw.get("dataset") or {}).get("formatting"),
            "columns": raw.get("columns") or (raw.get("dataset") or {}).get("columns"),
            "tags": raw.get("tags") or (raw.get("dataset") or {}).get("tags"),
        }
        parameters = dict(raw.get("parameters") or {})
        # Existing API payloads keep a few controls at task level. Fold them
        # into the canonical LLaMA-Factory parameter model here so old clients
        # and the new executor share one conversion path.
        if raw.get("validationSplit") is not None:
            parameters.setdefault("validationSplit", raw["validationSplit"])
        if raw.get("maxSteps") is not None:
            parameters.setdefault("maxSteps", raw["maxSteps"])
        parameters.update(dict(raw.get("extraParameters") or {}))
        # These are platform/UI controls, not LLaMA-Factory YAML options.
        # Keep them in the task API contract but never leak camelCase extras
        # into the strict YAML conversion path.
        validation_steps = parameters.pop("validationSteps", None)
        if validation_steps is not None:
            parameters.setdefault("evalSteps", validation_steps)
        parameters.setdefault("loraPlusEnabled", False)
        if not parameters["loraPlusEnabled"]:
            parameters.pop("loraPlusRatio", None)
        parameters.setdefault("checkpointLimit", max(1, int(raw.get("checkpointLimit") or 2)))
        parameters.setdefault("checkpointStrategy", raw.get("checkpointStrategy") or "epoch")
        parameters.setdefault("checkpointInterval", max(1, int(raw.get("checkpointInterval") or 100)))
        parameters.setdefault("useCpu", True)
        raw["parameters"] = parameters
        return LlamaFactoryTask.model_validate(raw)

    async def prepare(self, task: Mapping[str, Any]) -> ExecutionHandle:
        task_id = self._task_id(task)
        workdir = (self.work_root / task_id).resolve()
        if workdir == self.work_root or self.work_root not in workdir.parents:
            raise ValueError("任务工作目录越界。")
        workdir.mkdir(parents=True, exist_ok=True)
        dataset_dir = workdir / "dataset"
        dataset_dir.mkdir(parents=True, exist_ok=True)
        output_dir = workdir / "output"
        output_dir.mkdir(parents=True, exist_ok=True)

        raw_paths = dict((task.get("dataset") or {}).get("paths") or {})
        raw_paths.update({key: task[key] for key in ("trainPath", "validationPath", "testPath", "challengePath") if task.get(key)})
        if not raw_paths.get("trainPath"):
            raise ValueError("训练任务缺少 trainPath。")
        copied_paths: dict[str, str] = {}
        for key, source_value in raw_paths.items():
            if not source_value:
                continue
            source = Path(str(source_value)).expanduser().resolve()
            if not source.is_file():
                raise ValueError(f"数据文件不存在：{source}")
            target = dataset_dir / source.name
            if source != target:
                shutil.copy2(source, target)
            copied_paths[key] = str(target)

        canonical = self._canonical_task({**dict(task), "dataset": {"paths": copied_paths}}, output_dir)
        config = platform_to_llamafactory_config(canonical, output_dir=output_dir, allowed_roots=[workdir])
        # LLaMA-Factory resolves dataset file names relative to dataset_dir.
        (dataset_dir / "dataset_info.json").write_text(
            json.dumps(dataset_info_for_task(canonical), ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        config_path = workdir / "train.yaml"
        config_path.write_text(dump_yaml(config), encoding="utf-8")
        handle = ExecutionHandle(task_id=task_id, workdir=str(workdir), config_path=str(config_path), prepared=True)
        self._handles[task_id] = handle
        return handle

    async def start(self, task: Mapping[str, Any]) -> ExecutionHandle:
        task_id = self._task_id(task)
        handle = self._handles.get(task_id)
        if handle is None or not handle.prepared:
            handle = await self.prepare(task)
        if handle.process is not None and handle.process.returncode is None:
            return handle
        argv = self._launch_argv(handle.config_path)
        environment = os.environ.copy()
        environment["PYTHONUNBUFFERED"] = "1"
        handle.process = await asyncio.create_subprocess_exec(
            *argv,
            cwd=handle.workdir,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.STDOUT,
            env=environment,
        )
        return handle

    async def stop(self, task: Mapping[str, Any]) -> None:
        handle = self._handles.get(self._task_id(task))
        process = handle.process if handle else None
        if process is None or process.returncode is not None:
            return
        process.terminate()
        try:
            await asyncio.wait_for(process.wait(), timeout=self.stop_timeout)
        except asyncio.TimeoutError:
            process.kill()
            await process.wait()

    async def status(self, task: Mapping[str, Any]) -> dict[str, Any]:
        handle = self._handles.get(self._task_id(task))
        if handle is None:
            return {"state": "not_prepared"}
        process = handle.process
        if process is None:
            return {"state": "prepared", "workdir": handle.workdir, "configPath": handle.config_path}
        if process.returncode is None:
            return {"state": "running", "pid": process.pid, "workdir": handle.workdir, "configPath": handle.config_path}
        return {"state": "completed" if process.returncode == 0 else "failed", "returncode": process.returncode, "workdir": handle.workdir, "configPath": handle.config_path}

    async def events(self, task: Mapping[str, Any]) -> AsyncIterator[TrainingEvent]:
        handle = self._handles.get(self._task_id(task))
        if handle is None or handle.process is None or handle.process.stdout is None:
            return
        total_steps: int | None = None
        total_epochs: float | None = None
        last_train_step = 0
        task_parameters = dict(task.get("parameters") or {})
        logging_steps = max(1, int(task_parameters.get("loggingSteps", 10)))
        while True:
            try:
                line = await asyncio.wait_for(handle.process.stdout.readline(), timeout=0.5)
            except asyncio.TimeoutError:
                yield TrainingEvent("heartbeat")
                continue
            if not line:
                await handle.process.wait()
                break
            text = line.decode("utf-8", errors="replace").strip()
            if not text:
                continue
            if text.startswith("__XUNTUI_EVENT__"):
                try:
                    payload = json.loads(text.removeprefix("__XUNTUI_EVENT__"))
                    yield TrainingEvent(str(payload.get("type", "log")), str(payload.get("message", "")), payload)
                    continue
                except json.JSONDecodeError:
                    pass
            steps_match = TOTAL_STEPS_PATTERN.search(text)
            if steps_match:
                total_steps = int(steps_match.group(1).replace(",", ""))
            epochs_match = NUM_EPOCHS_PATTERN.search(text)
            if epochs_match:
                total_epochs = float(epochs_match.group(1))
            values = parse_trainer_values(text)
            if values:
                step = infer_metric_step(
                    values,
                    total_steps=total_steps,
                    total_epochs=total_epochs,
                    last_train_step=last_train_step,
                    logging_steps=logging_steps,
                )
                if "loss" in values:
                    last_train_step = step
                payload = {**values, "step": step}
                if total_steps:
                    payload["total_steps"] = total_steps
                    payload["progress"] = min(95, int(step * 95 / total_steps))
                yield TrainingEvent("metric", text, payload)
            else:
                yield TrainingEvent("log", text, {"raw": text})

    async def collect_artifacts(self, task: Mapping[str, Any]) -> list[dict[str, Any]]:
        task_id = self._task_id(task)
        handle = self._handles.get(task_id)
        workdir = Path(handle.workdir) if handle else self.work_root / task_id
        output = workdir / "output"
        if not output.is_dir():
            raise FileNotFoundError(f"训练输出目录不存在：{output}")
        remote_workdir = getattr(handle, "remote_workdir", None)
        artifacts = read_training_artifacts(
            output, remote_output=task.get("_remoteOutputDir") or (f"{remote_workdir}/output" if remote_workdir else None),
        )
        manifest_entries: list[dict[str, Any]] = []
        for path in sorted(output.rglob("*")):
            if not path.is_file():
                continue
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            manifest_entries.append({"relativePath": str(path.relative_to(workdir)).replace("\\", "/"), "sizeBytes": path.stat().st_size, "sha256": digest, "fileType": path.suffix.lstrip(".") or "file"})
        manifest = {"taskId": task_id, "model": task.get("model"), "datasetId": task.get("datasetId"), "generatedAt": datetime.now(timezone.utc).isoformat(), "files": manifest_entries}
        manifest_path = workdir / "manifest.json"
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        artifacts.append({"type": "manifest", "name": "manifest", "path": str(manifest_path), "sha256": hashlib.sha256(manifest_path.read_bytes()).hexdigest()})
        return artifacts

    async def cleanup(self, task: Mapping[str, Any]) -> None:
        task_id = self._task_id(task)
        await self.stop(task)
        self._handles.pop(task_id, None)


__all__ = ["LocalLlamaFactoryExecutor"]
