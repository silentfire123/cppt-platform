"""Remote launch regression: loss must be readable before the trainer exits."""
from __future__ import annotations

import asyncio
import os
import shlex
import subprocess
import sys
import time
from types import SimpleNamespace

from backend.test_youyun_remote_training import FakeSink, FakeSSH, RunnerTestBase


class TrainingLogStreamTest(RunnerTestBase):
    def test_first_loss_is_ingested_while_trainer_is_still_running(self) -> None:
        # Exercise both a direct trainer and a launcher that spawns a Python worker.
        # SSH is replaced, but file buffering, worker inheritance, log following,
        # parsing and metric ingestion are real. No GPU or remote service is used.
        for spawn_worker in (False, True):
            with self.subTest(spawn_worker=spawn_worker):
                sink = FakeSink()
                log_path = self.mirror / f"train-{spawn_worker}.log"
                ready_path = self.mirror / f"ready-{spawn_worker}"
                process = None
                case = self
                worker = (
                    "import sys; from pathlib import Path; "
                    "print('Total optimization steps = 20', file=sys.stderr, flush=True); "
                    "print('Num Epochs = 1', file=sys.stderr, flush=True); "
                    "print({'loss': 1.843, 'epoch': 0.05}); "
                    "print('1/20', file=sys.stderr, flush=True); "
                    f"Path({str(ready_path)!r}).touch(); "
                    "sys.stdin.readline()"
                )
                script = (
                    "import subprocess, sys; "
                    f"sys.exit(subprocess.call([sys.executable, '-c', {worker!r}]))"
                    if spawn_worker else worker
                )

                with log_path.open("wb") as log_file:
                    class FileBackedSSH(FakeSSH):
                        def log_connection(self):
                            from backend.test_remote_log_follow import LocalLogSSH
                            class FileLogSSH(LocalLogSSH):
                                def follow_log(self, command, stop):
                                    args = shlex.split(command)
                                    args[0] = sys.executable
                                    args[-4] = str(log_path)
                                    yield from super().follow_log(shlex.join(args), stop)
                            return FileLogSSH()

                        def run(self, command, timeout=120, check=True):
                            nonlocal process
                            if "nohup" in command and "train.yaml" in command:
                                # Read the environment attached to the actual Python
                                # invocation generated by _train_and_follow, not a
                                # separately maintained copy of its launch options.
                                shell_tokens = shlex.split(command)
                                runner_script = shell_tokens[shell_tokens.index("bash") + 2]
                                train_tokens = shlex.split(runner_script.split(";")[-2])
                                python_index = train_tokens.index("$PY")
                                environment = os.environ.copy()
                                environment.pop("PYTHONUNBUFFERED", None)
                                for token in train_tokens[:python_index]:
                                    key, value = token.split("=", 1)
                                    environment[key] = value
                                process = subprocess.Popen(
                                    [sys.executable, "-c", script],
                                    stdin=subprocess.PIPE,
                                    stdout=log_file,
                                    stderr=subprocess.STDOUT,
                                    env=environment,
                                )
                                deadline = time.monotonic() + 5
                                while not ready_path.exists() and time.monotonic() < deadline:
                                    case.assertIsNone(process.poll(), "trainer exited before readiness")
                                    time.sleep(0.01)
                                case.assertTrue(ready_path.exists(), "trainer did not become ready")
                                return 0, ""
                            if command.startswith("echo code:"):
                                self.train_poll_count += 1
                                case.assertIsNotNone(process)
                                case.assertIsNone(process.poll(), "must check loss before trainer exit")
                                if self.train_poll_count == 1:
                                    return 0, "code:none\n" + log_path.read_text(encoding="utf-8")
                                deadline = time.monotonic() + .9
                                while (not sink.metrics or "1/20" not in sink.logs) and time.monotonic() < deadline:
                                    time.sleep(.01)
                                case.assertIn("1/20", sink.logs)
                                case.assertEqual(
                                    len(sink.metrics), 1,
                                    "first loss is buffered even though progress is already readable",
                                )
                                case.assertEqual(sink.metrics[0]["step"], 1)
                                case.assertAlmostEqual(sink.metrics[0]["train_loss"], 1.843)
                                process.communicate(b"\n", timeout=5)
                                return 0, "code:0\n"
                            return super().run(command, timeout, check)

                    ssh = FileBackedSSH()
                    runner = self.make_runner(sink)
                    try:
                        result = asyncio.run(runner._train_and_follow(
                            "t-stream", {"parameters": {"loggingSteps": 5}}, ssh,
                            SimpleNamespace(remote_workdir="/root/cppt/t-stream"),
                        ))
                        self.assertEqual(result, 0)
                    finally:
                        if process is not None:
                            if process.poll() is None:
                                process.communicate(b"\n", timeout=5)
                            elif process.stdin is not None:
                                process.stdin.close()
